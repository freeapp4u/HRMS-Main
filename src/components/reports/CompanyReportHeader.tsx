import React from "react";
import { CompanyConfig } from "../../types";
import {
  formatReportDateTime,
  getCompanyLogoUrl,
  OFFICIAL_COMPANY_LEGAL_NAME,
  OFFICIAL_COMPANY_NAME,
} from "../../utils/reportBranding";

export interface CompanyReportHeaderProps {
  companyConfig?: CompanyConfig;
  logoUrl?: string;
  reportTitle: string;
  reportSubtitle?: string;
  reportingPeriod?: string;
  departmentOrUnit?: string;
  generatedAt?: string;
  generatedBy?: string;
  referenceNo?: string;
  extraMeta?: { label: string; value: string }[];
}

export default function CompanyReportHeader({
  companyConfig,
  logoUrl,
  reportTitle,
  reportSubtitle,
  reportingPeriod,
  departmentOrUnit,
  generatedAt,
  generatedBy,
  referenceNo,
  extraMeta,
}: CompanyReportHeaderProps) {
  const effectiveLogoSrc = getCompanyLogoUrl(companyConfig, logoUrl);
  const timestamp = generatedAt || formatReportDateTime();

  const legalName = companyConfig?.profile?.legalName || OFFICIAL_COMPANY_LEGAL_NAME;
  const addressLine = [
    companyConfig?.profile?.address,
    companyConfig?.profile?.city,
    companyConfig?.profile?.country,
  ]
    .filter(Boolean)
    .join(", ");

  const metaItems: { label: string; value: string }[] = [
    { label: "Generated", value: timestamp },
    ...(reportingPeriod ? [{ label: "Reporting Period", value: reportingPeriod }] : []),
    ...(departmentOrUnit ? [{ label: "Department / Unit", value: departmentOrUnit }] : []),
    ...(generatedBy ? [{ label: "Generated By", value: generatedBy }] : []),
    ...(referenceNo ? [{ label: "Reference No", value: referenceNo }] : []),
    ...(extraMeta || []),
  ];

  return (
    <div className="space-y-4 mb-6">
      {/* Official Corporate Letterhead */}
      <div className="border-b-2 border-primary-custom pb-4 flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
        <div className="flex items-center gap-3.5">
          <img
            src={effectiveLogoSrc}
            alt="Ethiopian Reinsurance S.C. Official Logo"
            className="h-16 w-auto max-w-[140px] object-contain shrink-0 rounded"
            referrerPolicy="no-referrer"
          />
          <div>
            <h1 className="font-black text-primary-custom text-sm md:text-base tracking-tight uppercase">
              {OFFICIAL_COMPANY_NAME}
            </h1>
            <p className="text-[11px] font-bold text-slate-600">
              {legalName} • Human Resource Management System
            </p>
            {addressLine && (
              <p className="text-[10px] text-slate-400 font-medium mt-0.5">{addressLine}</p>
            )}
          </div>
        </div>

        <div className="text-left sm:text-right text-[10px] font-medium text-slate-500 leading-relaxed">
          {companyConfig?.profile?.email && <div>Email: {companyConfig.profile.email}</div>}
          {companyConfig?.profile?.phoneNumber && <div>Phone: {companyConfig.profile.phoneNumber}</div>}
          {companyConfig?.profile?.website && <div>Website: {companyConfig.profile.website}</div>}
        </div>
      </div>

      {/* Gold Accent Rule */}
      <div className="h-0.5 bg-accent-custom -mt-3 rounded-full" />

      {/* Standard Report Title & Metadata Banner */}
      <div className="bg-slate-50 border border-slate-200 rounded-lg px-4 py-3 flex flex-col sm:flex-row justify-between items-start sm:items-end gap-3 text-xs">
        <div>
          <h2 className="text-sm md:text-base font-extrabold text-slate-900 uppercase tracking-tight">
            {reportTitle}
          </h2>
          {reportSubtitle && (
            <p className="text-[11px] text-slate-600 font-medium mt-0.5">{reportSubtitle}</p>
          )}
        </div>

        <div className="text-left sm:text-right text-[10px] text-slate-600 space-y-0.5 shrink-0">
          {metaItems.map((item, idx) => (
            <div key={`${item.label}-${idx}`}>
              <span className="font-bold text-slate-500">{item.label}: </span>
              <span className="font-bold text-slate-800">{item.value}</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
